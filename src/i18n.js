// Language of the app: Czech (the texts in the code) or English (this dictionary).
// t('Přidat složku') gives the text in the current language; {name} parts are filled from
// the second argument. Loaded before main.js, which switches the language (setLanguage).

let LANG = 'cs';

const LOCALES = { cs: 'cs-CZ', en: 'en-GB' };
const locale = () => LOCALES[LANG];

function t(text, params) {
  const s = LANG === 'en' && Object.hasOwn(EN, text) ? EN[text] : text;
  return params ? s.replace(/\{(\w+)\}/g, (all, key) => (key in params ? params[key] : all)) : s;
}

/** Number with `digits` decimals in the current language ("1,5" / "1.5"). */
function num(x, digits = 0) {
  return x.toLocaleString(locale(), { minimumFractionDigits: digits, maximumFractionDigits: digits });
}

/** English noun for a count, by the Czech singular used in the code; undefined when unknown. */
function pluralEn(n, czechOne) {
  const forms = EN_PLURALS[czechOne];
  return forms && (n === 1 ? forms[0] : forms[1]);
}

/** Translates the elements of index.html marked with data-t, data-t-title or data-t-placeholder. */
function translatePage() {
  document.documentElement.lang = LANG;
  for (const el of document.querySelectorAll('[data-t]')) {
    el.dataset.t ||= el.textContent.trim();
    el.textContent = t(el.dataset.t);
  }
  for (const el of document.querySelectorAll('[data-t-title]')) el.title = t(el.dataset.tTitle);
  for (const el of document.querySelectorAll('[data-t-placeholder]')) el.placeholder = t(el.dataset.tPlaceholder);
}

